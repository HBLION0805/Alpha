/** Render knowledge/catalog.json (verbatim data extracted from the legacy catalogs) into readable markdown. Text is copied, never rewritten. */
import { readFileSync, writeFileSync } from "node:fs";

type Item = { id: string; group: string; title: string; status: string; topics: string[]; principle: string; application: string; limits: string; destination: string; sources: string[] };
const c = JSON.parse(readFileSync("knowledge/catalog.json", "utf8")) as {
  version: string; contentRevision: string; reviewedDateNewYork: string; boundary: string;
  sources: Array<{ id: string; title: string; url: string | null; coverage: string }>;
  items: Item[]; fields: Array<{ id: string; label: string; prompt: string }>;
  psychology: { revision: string; boundary: string; biases: Array<{ id: string; title: string; group: string; prompt: string; status: string }>; prompts: Array<{ id: string; stage: string; title: string; text: string }>; adoption: Array<{ status: string; title: string; text: string }> };
};
const hdr = (t: string) => `# ${t}\n\n_Verbatim from \`knowledge/catalog.json\` (${c.version}, revision ${c.contentRevision}, reviewed ${c.reviewedDateNewYork}). Generated by scripts/render-knowledge.ts — edit the JSON, not this file._\n\n`;

let md = hdr("Macro playbook & psychology knowledge items") + `> ${c.boundary}\n\n`;
for (const g of [...new Set(c.items.map((i) => i.group))]) {
  md += `## ${g}\n\n`;
  for (const i of c.items.filter((x) => x.group === g)) {
    md += `### ${i.title}\n\n- **id:** \`${i.id}\` · **status:** ${i.status} · **destination:** ${i.destination}\n- **topics:** ${i.topics.join("; ")}\n- **sources:** ${i.sources.join(", ")}\n\n**Principle.** ${i.principle}\n\n**Application.** ${i.application}\n\n**Limits.** ${i.limits}\n\n`;
  }
}
writeFileSync("knowledge/PLAYBOOK.md", md);

let b = hdr("Bias reflection questions") + `> ${c.psychology.boundary}\n\n| # | id | bias | group | question | status |\n|---|---|---|---|---|---|\n`;
c.psychology.biases.forEach((x, n) => (b += `| ${n + 1} | ${x.id} | ${x.title} | ${x.group} | ${x.prompt.replace(/\|/g, "\\|")} | ${x.status} |\n`));
writeFileSync("knowledge/BIAS_QUESTIONS.md", b);

let p = hdr("Phase prompts (before entry / while holding / after a decision)");
for (const st of [...new Set(c.psychology.prompts.map((x) => x.stage))]) {
  p += `## ${st}\n\n`;
  for (const x of c.psychology.prompts.filter((y) => y.stage === st)) p += `- **${x.title}** (\`${x.id}\`) — ${x.text}\n`;
  p += "\n";
}
p += "## Adoption status\n\n";
for (const a of c.psychology.adoption) p += `- **${a.status} — ${a.title}:** ${a.text}\n`;
writeFileSync("knowledge/PHASE_PROMPTS.md", p);

let w = hdr("Trade worksheet fields");
c.fields.forEach((f, n) => (w += `${n + 1}. **${f.label}** (\`${f.id}\`) — ${f.prompt}\n`));
writeFileSync("knowledge/WORKSHEET.md", w);

let s = hdr("Sources");
for (const x of c.sources) s += `- **${x.title}** (\`${x.id}\`)${x.url ? ` — ${x.url}` : ""}\n  ${x.coverage}\n`;
writeFileSync("knowledge/SOURCES.md", s);
console.log(`items ${c.items.length}, biases ${c.psychology.biases.length}, prompts ${c.psychology.prompts.length}, fields ${c.fields.length}, sources ${c.sources.length}`);
